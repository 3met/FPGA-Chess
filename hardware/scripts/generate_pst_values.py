"""Generate the PST readmemh file used by RTL and test benches."""

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
PST_WORD_BITS = 10
PST_JSON_PATH = ROOT / "hardware" / "data" / "pst_values" / "pst_values.json"
PST_HEX_PATH = ROOT / "hardware" / "data" / "pst_values" / "pst_values.hex"
PST_ENDGAME_HEX_PATH = ROOT / "hardware" / "data" / "pst_values" / "pst_values_endgame.hex"
MATERIAL_SV_PATH = ROOT / "hardware" / "rtl" / "generated" / "evaluation_parameters.svh"
PIECE_ORDER = ["pawn", "knight", "bishop", "rook", "queen", "king"]


def load_pst_words(json_path, key="pst"):
    """Load one phase's six signed piece-square tables."""
    with json_path.open() as f:
        data = json.load(f)

    pst = data[key]
    mem = [0] * (len(PIECE_ORDER) * 64)

    for piece_idx, piece in enumerate(PIECE_ORDER):
        table = pst[piece]
        if len(table) != 64:
            raise ValueError(f"PST for {piece} has {len(table)} entries, expected 64")

        for square, value in enumerate(table):
            if not isinstance(value, int) or not -(1 << (PST_WORD_BITS - 1)) <= value < (1 << (PST_WORD_BITS - 1)):
                raise ValueError(f"PST value for {piece} square {square} does not fit signed {PST_WORD_BITS} bits: {value}")
            mem[(piece_idx << 6) | square] = value

    return mem


def load_material_values(json_path, key="material"):
    """Load one phase's material values in PieceType order."""
    with json_path.open() as f:
        material = json.load(f)[key]
    if set(material) != set(PIECE_ORDER):
        raise ValueError("material must define exactly the six chess piece types")
    values = [material[piece] for piece in PIECE_ORDER]
    if any(not isinstance(value, int) or not -4095 <= value <= 4095 for value in values):
        raise ValueError("material values must fit the negatable search-score range")
    return values


def phase_score_bound(material, words):
    """Bound a legal board using original pieces and at most eight promotions per side."""
    extrema = {}
    for index, piece in enumerate(PIECE_ORDER):
        scores = [material[index] + value for value in words[index * 64:(index + 1) * 64]]
        if min(scores) < -4095 or max(scores) > 4095:
            raise ValueError(f"material plus PST for {piece} must fit the negatable search-score range")
        extrema[piece] = (min(scores), max(scores))
    # Captures can remove any non-king; each pawn can remain or promote to any piece.
    # Root loading can temporarily omit a king while constructing the board.
    lower, upper = min(0, extrema["king"][0]), max(0, extrema["king"][1])
    for piece, count in (("knight", 2), ("bishop", 2), ("rook", 2), ("queen", 1)):
        lower += count * min(0, extrema[piece][0])
        upper += count * max(0, extrema[piece][1])
    lower += 8 * min(0, *(extrema[piece][0] for piece in PIECE_ORDER if piece != "king"))
    upper += 8 * max(0, *(extrema[piece][1] for piece in PIECE_ORDER if piece != "king"))
    # Opposing colors use mirrored copies of the same tables, with opposite signs.
    return upper - lower


def write_readmemh(words, out_path, word_bits=PST_WORD_BITS):
    hex_digits = (word_bits + 3) // 4
    mask = (1 << word_bits) - 1

    with out_path.open("w") as f:
        for word in words:
            f.write(f"{word & mask:0{hex_digits}X}\n")


def write_material_include(values, endgame_values, out_path, score_bound):
    """Generate both RTL material tables from the same JSON as the PSTs."""
    out_path.parent.mkdir(parents=True, exist_ok=True)
    def literals_for(phase_values):
        return ["'d0", *(f"-'d{-value}" if value < 0 else f"'d{value}" for value in phase_values), "'dx"]
    lines = [
        "// Generated by hardware/scripts/generate_pst_values.py; do not edit by hand.",
        "// Material values are in units of 1/128 pawn and indexed by PieceType.",
        f"localparam int PST_EVAL_BOUND = {score_bound};",
        "localparam int PST_EVAL_BITS = $clog2(PST_EVAL_BOUND + 1) + 1;",
        "localparam EvalScore PIECE_VALS_128[8] = '{",
        "\t" + ", ".join(literals_for(values)),
        "};",
        "localparam EvalScore PIECE_VALS_ENDGAME_128[8] = '{",
        "\t" + ", ".join(literals_for(endgame_values)),
        "};",
        "",
    ]
    out_path.write_text("\n".join(lines), encoding="ascii")


def main():
    words = load_pst_words(PST_JSON_PATH)
    endgame_words = load_pst_words(PST_JSON_PATH, "pst_endgame")
    material = load_material_values(PST_JSON_PATH)
    endgame_material = load_material_values(PST_JSON_PATH, "material_endgame")
    score_bound = max(phase_score_bound(material, words), phase_score_bound(endgame_material, endgame_words))
    write_readmemh(words, PST_HEX_PATH)
    write_readmemh(endgame_words, PST_ENDGAME_HEX_PATH)
    write_material_include(material, endgame_material, MATERIAL_SV_PATH, score_bound)
    print(f"Wrote PST HEX to {PST_HEX_PATH}")
    print(f"Wrote material SV include to {MATERIAL_SV_PATH}")


if __name__ == "__main__":
    main()
